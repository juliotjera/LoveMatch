-- LoveMatch : schéma (PostgreSQL en production, H2 en mode PostgreSQL pour le développement et les tests)

create table ville (
    id          bigint generated by default as identity primary key,
    nom         varchar(80)  not null unique,
    region      varchar(80)  not null,
    latitude    double precision not null,
    longitude   double precision not null
);

create table interet (
    id          bigint generated by default as identity primary key,
    code        varchar(40)  not null unique,
    libelle_fr  varchar(60)  not null,
    libelle_mg  varchar(60)  not null
);

create table utilisateur (
    id                bigint generated by default as identity primary key,
    email             varchar(190) not null unique,
    mot_de_passe      varchar(100) not null,
    prenom            varchar(60)  not null,
    nom               varchar(60)  not null,
    date_naissance    date         not null,
    genre             varchar(10)  not null,
    ville_id          bigint       not null references ville (id),
    bio               varchar(500),
    recherche         varchar(20)  not null,
    genre_recherche   varchar(10)  not null,
    age_min           int          not null,
    age_max           int          not null,
    rayon_km          int          not null,
    role              varchar(10)  not null,
    statut            varchar(10)  not null,
    demo              boolean      not null default false,
    cree_le           timestamp    not null,
    derniere_activite timestamp    not null,
    constraint ck_utilisateur_ages check (age_min >= 18 and age_max >= age_min and age_max <= 99),
    constraint ck_utilisateur_rayon check (rayon_km between 10 and 1000)
);

create table utilisateur_interet (
    utilisateur_id bigint not null references utilisateur (id) on delete cascade,
    interet_id     bigint not null references interet (id),
    primary key (utilisateur_id, interet_id)
);

create table photo (
    id             bigint generated by default as identity primary key,
    utilisateur_id bigint      not null references utilisateur (id) on delete cascade,
    contenu        bytea       not null,
    type_mime      varchar(30) not null,
    ordre          int         not null,
    cree_le        timestamp   not null
);
create index ix_photo_utilisateur on photo (utilisateur_id, ordre);

-- like ou « passer » : une seule réaction par paire (auteur, cible)
create table reaction (
    id        bigint generated by default as identity primary key,
    auteur_id bigint      not null references utilisateur (id) on delete cascade,
    cible_id  bigint      not null references utilisateur (id) on delete cascade,
    decision  varchar(10) not null,
    cree_le   timestamp   not null,
    constraint uq_reaction unique (auteur_id, cible_id)
);
create index ix_reaction_cible on reaction (cible_id, decision);

-- match mutuel : une seule ligne par paire, membre_a = le plus petit identifiant
create table correspondance (
    id         bigint generated by default as identity primary key,
    membre_a_id bigint    not null references utilisateur (id) on delete cascade,
    membre_b_id bigint    not null references utilisateur (id) on delete cascade,
    cree_le    timestamp  not null,
    ferme_le   timestamp,
    constraint uq_correspondance unique (membre_a_id, membre_b_id),
    constraint ck_correspondance_ordre check (membre_a_id < membre_b_id)
);

create table message (
    id                bigint generated by default as identity primary key,
    correspondance_id bigint        not null references correspondance (id) on delete cascade,
    auteur_id         bigint        not null references utilisateur (id) on delete cascade,
    contenu           varchar(1000) not null,
    envoye_le         timestamp     not null,
    lu_le             timestamp
);
create index ix_message_correspondance on message (correspondance_id, envoye_le);

create table notification (
    id                bigint generated by default as identity primary key,
    destinataire_id   bigint      not null references utilisateur (id) on delete cascade,
    type              varchar(10) not null,
    correspondance_id bigint      references correspondance (id) on delete cascade,
    lue               boolean     not null default false,
    cree_le           timestamp   not null
);
create index ix_notification_destinataire on notification (destinataire_id, lue, cree_le);

create table blocage (
    id        bigint generated by default as identity primary key,
    auteur_id bigint    not null references utilisateur (id) on delete cascade,
    cible_id  bigint    not null references utilisateur (id) on delete cascade,
    cree_le   timestamp not null,
    constraint uq_blocage unique (auteur_id, cible_id)
);

create table signalement (
    id          bigint generated by default as identity primary key,
    auteur_id   bigint       not null references utilisateur (id) on delete cascade,
    cible_id    bigint       not null references utilisateur (id) on delete cascade,
    message_id  bigint       references message (id) on delete set null,
    motif       varchar(30)  not null,
    commentaire varchar(500),
    statut      varchar(10)  not null,
    cree_le     timestamp    not null,
    traite_le   timestamp,
    traite_par  bigint       references utilisateur (id) on delete set null
);
create index ix_signalement_statut on signalement (statut, cree_le);
